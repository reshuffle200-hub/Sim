// ======================================================================
//  bundle.mjs — inline the whole simulator into one HTML file
//
//  WHY.  ES modules cannot be loaded from file:// -- the browser applies CORS
//  to module fetches and a local file has no origin, so every import fails.
//  That is fine on a web server and useless on a phone, where the realistic way
//  to keep a copy of something is one file in Files that opens in Safari.
//  Unzipping a folder and running a local web server is not a thing anybody
//  does on an iPhone.
//
//  This is not a step toward a build system.  The source stays plain ES modules
//  and `index.html` served over HTTP remains the way it is developed and
//  deployed; tools/stamp.mjs remains the deploy step.  This produces one extra
//  artifact for the one case the module system genuinely cannot serve.
//
//  HOW.  Every module in this project uses exactly two import forms --
//  `import * as NS from './x.js'` and a single named import -- and every export
//  is either `export function` or `export const`.  That is a small enough
//  grammar to handle honestly with string work, and the assertions below fail
//  loudly if a file ever stops fitting it, rather than silently emitting a
//  bundle with a missing export.
//
//  Each module becomes an IIFE returning its exports, evaluated in dependency
//  order, so module scope stays module scope and nothing leaks into globals.
//
//  Usage:  node tools/bundle.mjs   ->  dist/pwr-sim-standalone.html
// ======================================================================

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'dist');

const BUILD = readFileSync(join(ROOT, 'lib/version.js'), 'utf8')
  .match(/export const BUILD = '([^']+)'/)[1];

// ---------------------------------------------------------------- collect
const files = [
  ...readdirSync(join(ROOT, 'lib')).filter(f => f.endsWith('.js')).map(f => 'lib/' + f),
  ...readdirSync(join(ROOT, 'ui')).filter(f => f.endsWith('.js')).map(f => 'ui/' + f)
];

const IMPORT_NS = /^import \* as (\w+) from '([^']+)';?$/m;
const IMPORT_NAMED = /^import \{([^}]+)\} from '([^']+)';?$/m;

const mods = new Map();
for (const rel of files) {
  const src = readFileSync(join(ROOT, rel), 'utf8');
  const deps = [];
  let body = src;

  // strip and record every import
  body = body.replace(/^import .*$/gm, line => {
    const ns = line.match(IMPORT_NS);
    if (ns) { deps.push({ kind: 'ns', name: ns[1], spec: resolve(rel, ns[2]) }); return ''; }
    const nm = line.match(IMPORT_NAMED);
    if (nm) {
      deps.push({
        kind: 'named',
        names: nm[1].split(',').map(s => s.trim()).filter(Boolean),
        spec: resolve(rel, nm[2])
      });
      return '';
    }
    throw new Error(`${rel}: import form not handled by the bundler:\n  ${line}`);
  });

  // record and unwrap every export
  const exported = [];
  body = body.replace(/^export (function|const|let|var|class)\s+(\w+)/gm, (_, kind, name) => {
    exported.push(name);
    return `${kind} ${name}`;
  });
  const leftover = body.match(/^export\b.*$/m);
  if (leftover) throw new Error(`${rel}: export form not handled:\n  ${leftover[0]}`);
  if (!exported.length) throw new Error(`${rel}: no exports found -- parse probably failed`);

  mods.set(rel, { rel, body, deps, exported });
}

function resolve(from, spec) {
  const base = dirname(from);
  const parts = (base + '/' + spec).split('/');
  const out = [];
  for (const p of parts) {
    if (p === '.' || p === '') continue;
    if (p === '..') out.pop();
    else out.push(p);
  }
  return out.join('/');
}

// ---------------------------------------------------------------- order
// Depth-first topological sort. A cycle here would mean the bundle evaluates a
// module before its dependency, so it is an error rather than something to
// paper over.
const order = [];
const state = new Map();
(function sort() {
  const visit = (rel, stack) => {
    if (state.get(rel) === 'done') return;
    if (state.get(rel) === 'busy')
      throw new Error(`circular import: ${[...stack, rel].join(' -> ')}`);
    const m = mods.get(rel);
    if (!m) throw new Error(`missing module: ${rel}`);
    state.set(rel, 'busy');
    for (const d of m.deps) visit(d.spec, [...stack, rel]);
    state.set(rel, 'done');
    order.push(rel);
  };
  for (const rel of mods.keys()) visit(rel, []);
})();

// ---------------------------------------------------------------- emit
let js = `// pwr-sim ${BUILD} — single-file build, generated by tools/bundle.mjs\n`
       + `const __M = Object.create(null);\n`;

for (const rel of order) {
  const m = mods.get(rel);
  const head = m.deps.map(d => d.kind === 'ns'
    ? `const ${d.name} = __M['${d.spec}'];`
    : `const { ${d.names.join(', ')} } = __M['${d.spec}'];`).join('\n');
  js += `\n__M['${rel}'] = (() => {\n${head}\n${m.body}\nreturn { ${m.exported.join(', ')} };\n})();\n`;
}

// The shell's own script, with its imports rewritten the same way.
let shell = readFileSync(join(ROOT, 'index.html'), 'utf8');
const scriptRe = /<script type="module">([\s\S]*?)<\/script>/;
const scriptMatch = shell.match(scriptRe);
if (!scriptMatch) throw new Error('index.html: could not find the module script');

let main = scriptMatch[1].replace(/^import .*$/gm, line => {
  const ns = line.match(IMPORT_NS);
  if (ns) return `const ${ns[1]} = __M['${resolve('index.html', ns[2])}'];`;
  const nm = line.match(IMPORT_NAMED);
  if (nm) return `const { ${nm[1].split(',').map(s => s.trim()).join(', ')} } = `
              + `__M['${resolve('index.html', nm[2])}'];`;
  throw new Error(`index.html: import form not handled:\n  ${line}`);
});

const out = shell.replace(scriptRe,
  `<script type="module">\n${js}\n${main}\n</script>`);

mkdirSync(OUT, { recursive: true });
const dest = join(OUT, 'pwr-sim-standalone.html');
writeFileSync(dest, out);

console.log(`build ${BUILD}`);
console.log(`${order.length} modules inlined in dependency order`);
console.log(`  ${order.join('\n  ')}`);
console.log(`\n${(out.length / 1024).toFixed(0)} kB -> dist/pwr-sim-standalone.html`);
